/**
 * The agent guide, served from a folder of Markdown templates so it reads and diffs like docs:
 *   llms.txt                  the index (llmstxt.org): what this is, real example calls, links to the rest
 *   agents/*.md               concepts, endpoints, trust and limits, MCP
 *   skills/SKILL.md, *.md     a skill folder: a router plus one playbook per task (also the MCP prompts)
 * `/llms-full.txt` is assembled from them in the order given, so it never drifts from its parts. `{{origin}}` and any
 * `{{dotted.path}}` from `vars()` are filled per request; a placeholder with no value is left visible and reported by
 * `fillTemplate`, which the tests check. The parts that must match the code are generated, never written by hand:
 * `{{api.endpoints}}`, `{{api.tag.<slug>}}`, `{{api.unblock}}`, `{{mcp.tools}}`, `{{skills.<name>.playbooks}}`
 * (see `reference.ts`). Each skill folder is also published for discovery: `/.well-known/agent-skills/index.json`
 * and a deterministic archive per skill with references, or its SKILL.md alone.
 *
 * On Node the templates are read from `dir`; on Workers, which can't read a folder, from `files`: the module
 * `agent-api-kit guide` writes from the folder (`GUIDE_FILES`), checked current by a test with `guideModuleSource`.
 *
 * @example
 * serveGuide(app, { dir: join(APP_DIR, 'guide'), vars: () => ({ snapshot: store.snapshot, counts: store.counts }),
 *   full: ['llms.txt', 'agents/concepts.md', 'agents/endpoints.md', 'agents/trust.md', 'agents/mcp.md', 'skills/*'] })
 * serveGuide(app, { files: GUIDE_FILES, vars, full })      // Workers: import { GUIDE_FILES } from './guide.gen.js'
 */
import { readdirSync, readFileSync, existsSync } from 'node:fs'
import { join, relative } from 'node:path'
import type { Context, Hono } from 'hono'
import { CACHE } from '../core/cache.js'
import { frontmatterOf, recordMounted, mountedOf, sendPublic, skillsIndex, tarGz, WELL_KNOWN, type SkillArtifact } from '../core/discovery.js'
import { originOf } from '../core/hal.js'
import { problemResponse } from '../core/problem.js'
import { generatedVars, type OpenApiDoc } from './reference.js'

export const MARKDOWN = 'text/markdown; charset=utf-8'

/** `{{counts.recipes}}` → the value at that path; numbers get thousands separators. Unknown names stay as they are. */
export const fillTemplate = (template: string, vars: Record<string, unknown>) => {
  const missing = new Set<string>()
  const text = template.replace(/\{\{\s*([\w.-]+)\s*\}\}/g, (whole, path: string) => {
    const value = path.split('.').reduce<unknown>((at, key) => (at && typeof at === 'object' ? (at as Record<string, unknown>)[key] : undefined), vars)
    if (value === undefined || value === null) {
      missing.add(path)
      return whole
    }
    return typeof value === 'number' ? value.toLocaleString('en-US') : String(value)
  })
  return { text, missing: [...missing] }
}

/** Every Markdown/text file under `dir`, by its path relative to it (`skills/plan-a-week.md`). */
export const guideFiles = (dir: string) => {
  const files = new Map<string, string>()
  const walk = (folder: string) => {
    for (const entry of readdirSync(folder, { withFileTypes: true })) {
      const path = join(folder, entry.name)
      if (entry.isDirectory()) walk(path)
      else if (/\.(md|txt)$/.test(entry.name)) files.set(relative(dir, path), readFileSync(path, 'utf8'))
    }
  }
  if (existsSync(dir)) walk(dir)
  return files
}

/**
 * The guide's files as a TypeScript module (`GUIDE_FILES`), for runtimes that can't read a folder. Deterministic:
 * paths sorted, `/` separators. `agent-api-kit guide` writes the same text, and an app's test compares the two.
 *
 * @example
 * expect(readFileSync('src/guide.gen.ts', 'utf8')).toBe(guideModuleSource(guideFiles(GUIDE_DIR)))
 */
export const guideModuleSource = (files: Map<string, string>) =>
  `// Generated by \`agent-api-kit guide\` from the guide folder: edit the templates there, then run it again.\n` +
  `export const GUIDE_FILES: Record<string, string> = {\n` +
  [...files.entries()].map(([path, text]) => [path.split('\\').join('/'), text] as const).sort(([a], [b]) => (a < b ? -1 : a > b ? 1 : 0)).map(([path, text]) => `  ${JSON.stringify(path)}: ${JSON.stringify(text)},\n`).join('') +
  `}\n`

/** The parts of llms-full.txt in order; `folder/*` expands to that folder's files, `SKILL.md` first. */
export const fullOrder = (files: Map<string, string>, order: string[]) =>
  order.flatMap((entry) =>
    entry.endsWith('/*')
      ? [...files.keys()].filter((name) => name.startsWith(entry.slice(0, -1))).sort((a, b) => Number(b.endsWith('SKILL.md')) - Number(a.endsWith('SKILL.md')) || a.localeCompare(b))
      : files.has(entry) ? [entry] : [],
  )

/** The guide as served: its template files and a renderer that fills them for one origin. */
export type Guide = { files: Map<string, string>; render: (origin: string, name: string) => Promise<string> }

type Requester = { request: (input: string, init?: RequestInit) => Response | Promise<Response> }

export type GuideSource = { dir: string; files?: never } | { files: Map<string, string> | Record<string, string>; dir?: never }

export const serveGuide = (app: Hono<any, any, any> & Requester, { vars, full, ...source }: GuideSource & { vars: () => Record<string, unknown>; full: string[] }): Guide => {
  const files = source.files ? (source.files instanceof Map ? source.files : new Map(Object.entries(source.files))) : guideFiles(source.dir!)
  // The OpenAPI document only changes with a deploy: fetch it once per origin, in-process, with the caller's own
  // credentials (a private service answers the spec only to them); only a good answer is kept
  const docs = new Map<string, Promise<OpenApiDoc>>()
  const docOf = (origin: string, credentials: Record<string, string>) => {
    if (!docs.has(origin)) {
      const url = new URL(origin)
      const fetched = Promise.resolve(app.request(WELL_KNOWN.openapi, { headers: { 'x-forwarded-proto': url.protocol.slice(0, -1), 'x-forwarded-host': url.host, ...credentials } })).then((response) => {
        if (!response.ok) throw new Error(`the spec answered ${response.status}`)
        return response.json() as Promise<OpenApiDoc>
      })
      docs.set(origin, fetched)
      fetched.catch(() => docs.delete(origin))
    }
    return docs.get(origin)!
  }
  const credentialsOf = (c: Context) => Object.fromEntries((['authorization', 'cookie', 'cf-access-jwt-assertion'] as const).flatMap((name) => (c.req.header(name) ? [[name, c.req.header(name)!]] : [])))
  const render = async (origin: string, name: string, credentials: Record<string, string> = {}) => {
    const generated = generatedVars({ origin, doc: await docOf(origin, credentials), tools: mountedOf(app).mcp?.tools, resources: mountedOf(app).mcp?.resources, files })
    return fillTemplate(files.get(name)!, { origin, ...generated, ...vars() }).text
  }
  const send = (c: Context, body: string) => c.body(body, 200, { 'content-type': MARKDOWN, 'cache-control': CACHE.docs })

  app.get('/llms.txt', async (c) => (files.has('llms.txt') ? send(c, await render(originOf(c), 'llms.txt', credentialsOf(c))) : problemResponse(c, 'not_found')))
  app.get('/llms-full.txt', async (c) => {
    const parts = await Promise.all(fullOrder(files, full).map(async (name) => `<!-- ${name} -->\n\n${(await render(originOf(c), name, credentialsOf(c))).trim()}\n`))
    return send(c, parts.join('\n---\n\n'))
  })
  for (const folder of ['agents', 'skills']) {
    app.get(`/${folder}/*`, async (c) => {
      const name = c.req.path.slice(1)
      return files.has(name) ? send(c, await render(originOf(c), name, credentialsOf(c))) : problemResponse(c, 'not_found', { detail: `No ${name}. The index is /llms.txt.` })
    })
  }

  // Skills for discovery: a skill with references ships as one archive, a lone SKILL.md as itself
  const skillNames = [...files.keys()].flatMap((path) => path.match(/^skills\/([^/]+)\/SKILL\.md$/)?.[1] ?? [])
  const artifacts = async (origin: string, credentials: Record<string, string> = {}): Promise<SkillArtifact[]> =>
    Promise.all(
      skillNames.map(async (name) => {
        const own = [...files.keys()].filter((path) => path.startsWith(`skills/${name}/`))
        const skillMd = await render(origin, `skills/${name}/SKILL.md`, credentials)
        const { description = '' } = frontmatterOf(skillMd)
        if (own.length === 1) return { name, description, type: 'skill-md' as const, url: `/skills/${name}/SKILL.md`, bytes: skillMd, mediaType: MARKDOWN }
        const entries = await Promise.all(own.map(async (path): Promise<[string, string]> => [path.slice(`skills/${name}/`.length), await render(origin, path, credentials)]))
        return { name, description, type: 'archive' as const, url: `/.well-known/agent-skills/${name}.tar.gz`, bytes: tarGz(entries), mediaType: 'application/gzip' }
      }),
    )
  // The catalogs read artifacts synchronously: keep the last set built per origin
  const built = new Map<string, SkillArtifact[]>()
  const artifactsNow = async (origin: string, credentials: Record<string, string> = {}) => {
    const list = await artifacts(origin, credentials)
    built.set(origin, list)
    return list
  }
  recordMounted(app, { skills: (origin) => built.get(origin) ?? [], refreshSkills: artifactsNow })

  app.get(WELL_KNOWN.skillsIndex, async (c) => sendPublic(c, JSON.stringify(skillsIndex(originOf(c), await artifactsNow(originOf(c), credentialsOf(c))), null, 2), 'application/json'))
  app.get('/.well-known/agent-skills/:file', async (c) => {
    const skill = (await artifactsNow(originOf(c), credentialsOf(c))).find((one) => one.url === c.req.path)
    return skill ? sendPublic(c, skill.bytes, skill.mediaType) : problemResponse(c, 'not_found', { detail: `No ${c.req.path}. The index is ${WELL_KNOWN.skillsIndex}.` })
  })
  return { files, render }
}
