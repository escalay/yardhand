/**
 * Refreshes `src/tools.gen.ts` from the gateway: every tool the key may use, with its input schema as a TypeScript
 * type, so `gateway.call('<name>', args)` is checked. Run against your instance: `YARDHAND_URL=… YARDHAND_KEY=… pnpm gen`.
 */
import { writeFileSync } from 'node:fs'
import { typeOf } from '../src/schema-type.js'

const url = process.env.YARDHAND_URL
const key = process.env.YARDHAND_KEY
if (!url || !key) throw new Error('Set YARDHAND_URL (your instance) and YARDHAND_KEY (a client key)')

type Operation = {
  post: { summary?: string; requestBody: { content: { 'application/json': { schema: Record<string, unknown> } } } }
}
const response = await fetch(`${url}/api/tools/openapi.json`, { headers: { authorization: `Bearer ${key}` } })
if (!response.ok) throw new Error(`${url}/api/tools/openapi.json answered ${response.status}`)
const doc = (await response.json()) as { info: { version: string }; paths: Record<string, Operation> }
const tools = Object.entries(doc.paths)
  .flatMap(([path, operation]) => {
    const name = path.match(/^\/api\/tools\/(.+)\/calls$/)?.[1]
    return name
      ? [
          {
            name,
            summary: operation.post.summary,
            schema: operation.post.requestBody.content['application/json'].schema,
          },
        ]
      : []
  })
  .sort((a, b) => a.name.localeCompare(b.name))

const body = [
  '// Generated by `pnpm gen` from /api/tools/openapi.json: never edit by hand.',
  `// Tools version ${doc.info.version}, ${tools.length} tools.`,
  '',
  `export type ToolName = ${tools.map((tool) => JSON.stringify(tool.name)).join(' | ') || 'never'}`,
  '',
  'export type ToolArgs = {',
  ...tools.flatMap((tool) => [
    ...(tool.summary ? [`  /** ${tool.summary.replaceAll('*/', '* /')} */`] : []),
    `  ${JSON.stringify(tool.name)}: ${typeOf(tool.schema, '  ')}`,
  ]),
  '}',
  '',
].join('\n')
writeFileSync(new URL('../src/tools.gen.ts', import.meta.url), body)
console.log(`wrote src/tools.gen.ts: ${tools.length} tools (version ${doc.info.version})`)
